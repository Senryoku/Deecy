texture: zgpu.TextureHandle = .nil,
view: zgpu.TextureViewHandle = .nil,
/// Is in use?
valid: bool = false,
/// Should be displayed?
display: bool = true,
/// GPU texture is outdated?
dirty: bool = false,
data: [48 * 32 / 8]u8 = @splat(0),

pub fn init(self: *@This(), gctx: *zgpu.GraphicsContext, port: usize) void {
    self.create_texture(gctx);
    self.data = VMUScreenDefault[port];
    self.dirty = true;
}

pub fn deinit(self: *@This(), gctx: *zgpu.GraphicsContext) void {
    gctx.releaseResource(self.texture);
    gctx.releaseResource(self.view);
}

fn create_texture(self: *@This(), gctx: *zgpu.GraphicsContext) void {
    self.texture = gctx.createTexture(.{
        .usage = .{ .texture_binding = true, .copy_dst = true },
        .size = .{
            .width = 48,
            .height = 32,
            .depth_or_array_layers = 1,
        },
        .format = .bgra8_unorm,
        .mip_level_count = 1,
    });
    self.view = gctx.createTextureView(self.texture, .{});
}

/// Locks gctx_queue_mutex
pub fn upload_vmu_texture(self: *@This(), deecy: *Deecy) void {
    const colors = [2][3]u8{ // bgr
        .{ 152, 135, 92 }, // "white"
        .{ 104, 43, 40 }, // "black"
    };

    var pixels: [4 * 48 * 32]u8 = undefined;
    for (0..32) |r| {
        const row = self.data[6 * (31 - r) .. 6 * ((31 - r) + 1)];
        for (0..6) |c| {
            var byte = row[5 - c];
            for (0..8) |b| {
                const color: [3]u8 = colors[byte & 0x1];
                const idx = 4 * (48 * r + (8 * c + b));
                pixels[idx + 0] = color[0];
                pixels[idx + 1] = color[1];
                pixels[idx + 2] = color[2];
                pixels[idx + 3] = 255;
                byte >>= 1;
            }
        }
    }
    deecy.gctx_queue_mutex.lock(deecy.io) catch return;
    defer deecy.gctx_queue_mutex.unlock(deecy.io);
    deecy.gctx.queue.writeTexture(
        .{ .texture = deecy.gctx.lookupResource(self.texture).? },
        .{ .bytes_per_row = 4 * 48, .rows_per_image = 32 },
        .{ .width = 48, .height = 32 },
        u8,
        &pixels,
    );
    self.dirty = false;
}

